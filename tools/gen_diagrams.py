"""Generate architecture diagrams from the code so the docs never drift.

Outputs (Mermaid, rendered natively by GitHub):
  docs/architecture/generated/module-dependencies.md  actual module uses-graph (grimp)
  docs/architecture/generated/rag-graph.md            LangGraph RAG state machine

Usage:
  uv run python tools/gen_diagrams.py           # regenerate
  uv run python tools/gen_diagrams.py --check   # exit 1 if stale (pytest, pre-commit, CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

import grimp

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "docs" / "architecture" / "generated"
PACKAGE = "sdlcrag"

# Must match docs/architecture/01-module-view.md and [tool.importlinter] in pyproject.toml.
LAYERS: list[tuple[str, list[str]]] = [
    ("Presentation", ["cli", "api"]),
    ("Orchestration", ["orchestration"]),
    ("Application", ["evaluation", "generation", "extraction", "ingestion"]),
    ("Domain", ["retrieval", "visualization", "access"]),
    ("Infrastructure", ["indexing", "providers"]),
    ("Cross-cutting", ["core"]),
]

HEADER = (
    "<!-- GENERATED by tools/gen_diagrams.py. Do not edit by hand. -->\n"
    "<!-- Regenerate: uv run python tools/gen_diagrams.py -->\n\n"
)


def module_dependencies() -> str:
    graph = grimp.build_graph(PACKAGE)
    modules = [m for _, mods in LAYERS for m in mods]
    actual = sorted(
        (a, b)
        for a in modules
        for b in modules
        if a != b
        and graph.direct_import_exists(
            importer=f"{PACKAGE}.{a}", imported=f"{PACKAGE}.{b}", as_packages=True
        )
    )
    undocumented = sorted(
        m.split(".")[1] for m in graph.find_children(PACKAGE) if m.split(".")[1] not in modules
    )

    lines = [
        "# Module dependencies: as implemented",
        "",
        "Actual `import` relations between Module View elements, extracted from the source with "
        "[grimp](https://github.com/python-grimp/grimp). Compare this with the *intended* uses "
        "in [01-module-view.md](../01-module-view.md). Upward edges are blocked by import-linter.",
        "",
        "```mermaid",
        "flowchart TB",
    ]
    for i, (layer, mods) in enumerate(LAYERS):
        lines.append(f"  subgraph L{i}[{layer}]")
        lines.extend(f"    {m}[{m}]" for m in mods)
        lines.append("  end")
    lines.extend(f"  {a} --> {b}" for a, b in actual if b != "core")
    used_core = sorted(a for a, b in actual if b == "core")
    if used_core:
        lines.append(f"  {' & '.join(used_core)} -.-> core")
    lines.append("```")
    lines += [
        "",
        f"- Edges: {len(actual)} (dotted = uses `core`)",
        f"- Packages not in the Module View: {', '.join(undocumented) or 'none'}",
        "",
    ]
    return HEADER + "\n".join(lines)


def rag_graph() -> str:
    body: str
    try:
        from sdlcrag.generation.graph import build_rag_graph

        body = build_rag_graph().get_graph().draw_mermaid()
    except NotImplementedError:
        body = "flowchart LR\n  pending[RAG graph not implemented yet]"
    return (
        HEADER
        + "# RAG state machine (LangGraph): as implemented\n\n"
        + "Generated with `CompiledStateGraph.get_graph().draw_mermaid()`.\n\n"
        + f"```mermaid\n{body.strip()}\n```\n"
    )


def main(check: bool) -> int:
    outputs = {
        OUT_DIR / "module-dependencies.md": module_dependencies(),
        OUT_DIR / "rag-graph.md": rag_graph(),
    }
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Stale generated diagrams (run `uv run python tools/gen_diagrams.py`):")
        for p in stale:
            print(f"  {p}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
